import {spawnSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
if(process.platform!=='linux')throw Error('Gere os pacotes Linux em Linux/WSL ou pelo workflow do GitHub Actions.');
const arch=(process.argv[2]??process.arch).replace(/^--/,'');
if(!['x64','arm64'].includes(arch))throw Error('Arquitetura suportada: x64 ou arm64.');
const run=(args)=>{const r=spawnSync(process.execPath,args,{stdio:'inherit',env:{...process.env,ELECTRON_BUILDER_CACHE:path.resolve('.cache/builder-cache'),electron_config_cache:path.resolve('.cache/electron-downloads'),CSC_IDENTITY_AUTO_DISCOVERY:'false'}});if(r.error)throw r.error;if(r.status!==0)process.exit(r.status??1)};
fs.mkdirSync('.cache',{recursive:true});
run(['scripts/create-icon.mjs']);
run(['scripts/copy-runtime.mjs']);
run(['node_modules/typescript/bin/tsc','--noEmit']);
run(['node_modules/vite/bin/vite.js','build']);
run(['scripts/stage-desktop.mjs']);
run(['node_modules/electron-builder/cli.js','--config','electron-builder.cjs','--linux',`--${arch}`,'--publish','never']);
run(['scripts/verify-linux-release.mjs',arch]);
